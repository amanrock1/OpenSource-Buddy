"use strict";

const STORAGE_KEY = "opensource-buddy.saved.v1";
const LIST_FIELDS = ["skills", "roadmap", "questions", "testing"];
const $ = (id) => document.getElementById(id);

let current = null; // last displayed result {source, model, notice, input, analysis}

// Build DOM safely: all user/model text goes through textContent, never innerHTML.
function el(tag, props = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (k === "class") node.className = v;
    else if (k === "text") node.textContent = v;
    else if (k.startsWith("on")) node.addEventListener(k.slice(2), v);
    else node.setAttribute(k, v);
  }
  for (const c of children) if (c) node.append(c);
  return node;
}

// ---------------------------------------------------------- localStorage ---
function isValidRecord(r) {
  const a = r && r.analysis;
  return !!(r && typeof r.id === "string" && r.input && typeof r.input.title === "string" &&
    typeof r.input.description === "string" && a && typeof a.explanation === "string" &&
    ["beginner", "intermediate", "advanced"].includes(a.difficulty) &&
    LIST_FIELDS.every((f) => Array.isArray(a[f])));
}

function loadSaved() {
  try {
    const data = JSON.parse(localStorage.getItem(STORAGE_KEY) || "[]");
    return Array.isArray(data) ? data.filter(isValidRecord) : [];
  } catch (e) {
    return []; // malformed or storage blocked
  }
}

function writeSaved(list) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(list));
    return true;
  } catch (e) {
    showError("Could not save: browser storage is unavailable or full.");
    return false;
  }
}

function renderSaved() {
  const list = loadSaved();
  const ul = $("saved-list");
  ul.replaceChildren();
  $("saved-empty").hidden = list.length > 0;
  for (const rec of list) {
    const when = new Date(rec.savedAt).toLocaleString();
    ul.append(el("li", {},
      el("div", { class: "meta" },
        el("strong", { text: rec.input.title }),
        el("small", { text: `${rec.source === "ai" ? "AI analysis" : "Demo guidance"} · saved ${isNaN(new Date(rec.savedAt)) ? "earlier" : when}` })),
      el("button", { type: "button", class: "secondary", text: "Open",
        "aria-label": `Open saved issue: ${rec.input.title}`, onclick: () => showResult(rec) }),
      el("button", { type: "button", class: "danger", text: "Delete",
        "aria-label": `Delete saved issue: ${rec.input.title}`, onclick: () => deleteSaved(rec.id) })));
  }
}

function saveCurrent() {
  if (!current) return;
  const list = loadSaved();
  list.unshift({ id: String(Date.now()) + Math.random().toString(36).slice(2, 6),
    savedAt: new Date().toISOString(), source: current.source, model: current.model,
    input: current.input, analysis: current.analysis });
  if (writeSaved(list.slice(0, 50))) {
    renderSaved();
    $("save-btn").textContent = "Saved ✓";
    $("save-btn").disabled = true;
  }
}

function deleteSaved(id) {
  writeSaved(loadSaved().filter((r) => r.id !== id));
  renderSaved();
}

// --------------------------------------------------------------- results ---
function listPanel(title, items, ordered, cls = "") {
  return el("div", { class: cls === "wide" ? "panel wide" : "panel" },
    el("span", { class: "tag", text: "Generated suggestion" }),
    el("h3", { text: title }),
    el(ordered ? "ol" : "ul", { class: ordered ? "tasks" : cls === "pills" ? "pills" : "" },
      ...items.map((t) => ordered
        ? el("li", {}, el("label", { class: "step" }, el("input", { type: "checkbox" }), el("span", { text: t })))
        : el("li", { text: t }))));
}

function showResult(res) {
  current = res;
  const a = res.analysis;
  const box = $("results");
  box.hidden = false;
  box.replaceChildren();

  const isAI = res.source === "ai";
  const bannerText = isAI
    ? `Generated by AI model ${res.model}. It has not read the repository, so verify everything.`
    : (res.notice || "Demo guidance: rule-based suggestions, not AI analysis.");
  const card = el("div", { class: "card" },
    el("h2", { text: "Analysis" }),
    el("div", { class: `banner ${isAI ? "ai" : "demo"}`, text: bannerText }));

  const urlLine = res.input.url
    ? el("p", { class: "muted", text: `URL: ${res.input.url} (entered by you; not fetched or verified)` })
    : null;
  const facts = el("div", { class: "panel facts wide" },
    el("span", { class: "tag", text: "Your input (the only facts here)" }),
    el("h3", { text: res.input.title }),
    urlLine,
    el("p", { class: "muted", text: "Nothing in this tool was fetched from GitHub. Everything below is generated suggestion." }));

  const grid = el("div", { class: "grid" },
    facts,
    el("div", { class: "panel wide" },
      el("span", { class: "tag", text: "Generated suggestion" }),
      el("h3", { text: "Simple explanation" }),
      el("p", { text: a.explanation })),
    listPanel("Skills required", a.skills, false, "pills"),
    el("div", { class: "panel" },
      el("span", { class: "tag", text: "Generated estimate" }),
      el("h3", { text: "Difficulty estimate" }),
      el("p", {}, el("span", { class: `diff ${a.difficulty}`, text: a.difficulty })),
      el("div", { class: `meter ${a.difficulty}`, "aria-hidden": "true" }, el("span"), el("span"), el("span")),
      el("p", { text: a.difficulty_reason || "" })),
    listPanel("Contribution roadmap", a.roadmap, true, "wide"),
    listPanel("Questions to investigate", a.questions, false),
    listPanel("Testing checklist", a.testing, false));
  card.append(grid);

  const saved = loadSaved().some((r) => r.id === res.id);
  card.append(el("div", { class: "actions" },
    res.id && saved ? null : el("button", { id: "save-btn", type: "button", class: "primary",
      text: "Save this issue", onclick: saveCurrent }),
    el("button", { type: "button", class: "secondary", text: "Copy roadmap", onclick: copyRoadmap })));
  card.classList.add("fade-in");
  box.append(card);
  box.scrollIntoView({ behavior: "smooth", block: "start" });
}

function roadmapMarkdown(res) {
  const a = res.analysis;
  const bullets = (items) => items.map((t) => `- ${t}`).join("\n");
  return [`# ${res.input.title}`,
    `_${res.source === "ai" ? "AI-generated" : "Demo"} guidance, not verified against the repository._`,
    `\n**Difficulty (estimate):** ${a.difficulty}`, `\n## Roadmap`,
    a.roadmap.map((t, i) => `${i + 1}. ${t}`).join("\n"),
    `\n## Questions to investigate`, bullets(a.questions),
    `\n## Testing checklist`, bullets(a.testing)].join("\n");
}

async function copyRoadmap(ev) {
  if (!current) return;
  const btn = ev.currentTarget;
  const old = btn.textContent;
  try {
    await navigator.clipboard.writeText(roadmapMarkdown(current));
    btn.textContent = "Copied ✓";
  } catch (e) {
    btn.textContent = "Copy not allowed";
  }
  setTimeout(() => { btn.textContent = old; }, 1800);
}

function updateCount() {
  $("desc-count").textContent = `${$("description").value.length} / 8000`;
}

// ------------------------------------------------------------------ form ---
function showError(msg) {
  const p = $("form-error");
  p.textContent = msg;
  p.hidden = !msg;
}

function validate(v) {
  if (v.title.length < 3) return "Please enter an issue title (at least 3 characters).";
  if (v.description.length < 10) return "Please enter an issue description (at least 10 characters).";
  if (v.url && !/^https:\/\/github\.com\/[\w.-]+\/[\w.-]+\/(issues|pull)\/\d+\/?$/.test(v.url))
    return "URL must look like https://github.com/owner/repo/issues/123, or leave it empty.";
  return "";
}

async function onSubmit(ev) {
  ev.preventDefault();
  const v = { title: $("title").value.trim(), description: $("description").value.trim(),
    url: $("url").value.trim(), mode: $("demo-only").checked ? "demo" : "auto" };
  const problem = validate(v);
  showError(problem);
  if (problem) return;

  const btn = $("analyze-btn");
  btn.disabled = true;
  btn.textContent = "Analyzing…";
  const box = $("results");
  box.hidden = false;
  box.replaceChildren(el("div", { class: "card loading" }, el("div", { class: "spinner" }),
    el("span", { text: v.mode === "auto" ? "Analyzing… the AI model can take a minute." : "Preparing demo guidance…" })));
  try {
    const resp = await fetch("/api/analyze", { method: "POST",
      headers: { "Content-Type": "application/json" }, body: JSON.stringify(v) });
    let data = null;
    try { data = await resp.json(); } catch (e) { /* non-JSON error page */ }
    if (!resp.ok || !data) throw new Error((data && data.error) || `Server error (${resp.status}).`);
    data.id = null;
    showResult(data);
  } catch (e) {
    box.hidden = true;
    showError(e instanceof TypeError ? "Could not reach the server. Is the app still running?" : e.message);
  } finally {
    btn.disabled = false;
    btn.textContent = "Analyze Issue";
  }
}

function clearForm() {
  $("issue-form").reset();
  updateCount();
  showError("");
  $("results").hidden = true;
}

async function init() {
  $("issue-form").addEventListener("submit", onSubmit);
  $("clear-btn").addEventListener("click", clearForm);
  $("description").addEventListener("input", updateCount);
  renderSaved();

  try {
    const samples = await (await fetch("/api/samples")).json();
    $("sample-buttons").replaceChildren(...samples.map((s) => el("button", {
      type: "button", class: "chip", text: s.label,
      onclick: () => { $("title").value = s.title; $("description").value = s.description;
        $("url").value = ""; updateCount(); showError(""); $("title").focus(); } })));
  } catch (e) {
    $("sample-buttons").textContent = "(examples unavailable)";
  }

  const status = $("engine-status");
  try {
    const s = await (await fetch("/api/status")).json();
    status.dataset.state = s.ollama_available ? "ok" : "off";
    status.textContent = s.ollama_available
      ? `AI engine: ${s.message}`
      : `AI engine offline. Demo mode will be used. (${s.message})`;
  } catch (e) {
    status.dataset.state = "off";
    status.textContent = "Could not check AI engine status.";
  }
}

init();
